// The Clay relations as data: every `theorem relation_N : <statement>` of Qpu/Clay.lean, extracted into a TypeScript module so
// the pure handler can recompute them without a filesystem. Run by `npm run next` before the typecheck.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const ROOT = process.cwd()
const lean = readFileSync(join(ROOT, 'src/quantum/processing/unit/lean/Qpu/Clay.lean'), 'utf8')
const relations = [...lean.matchAll(/^theorem (relation_\d+) : (.+?) :=/gm)].map((m) => ({ name: m[1]!, statement: m[2]!.trim() }))
const out = `// GENERATED by scripts/gen-clay.ts from src/quantum/processing/unit/lean/Qpu/Clay.lean. Do not edit.
// The ${relations.length} Clay relations as the Lean file states them; the kernel accepted each by rfl.
export const CLAY_RELATIONS: readonly { name: string; statement: string }[] = ${JSON.stringify(relations, null, 2)}
`
writeFileSync(join(ROOT, 'src/quantum/clay-statements.ts'), out)
console.log(`gen-clay: ${relations.length} relations`)
