// The Clay relations as data: every `theorem relation_N : <statement>` of Qpu/Clay.lean, extracted into a TypeScript module so
// the pure handler can recompute them without a filesystem, each with the families of formulas its doc comment names it meets.
// Run by `npm run next` before the typecheck.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
const ROOT = process.cwd()
const lean = readFileSync(join(ROOT, 'src/quantum/processing/unit/lean/Qpu/Clay.lean'), 'utf8')
const lines = lean.split('\n')
const relations: { name: string; statement: string; families: string[] }[] = []
for (let i = 0; i < lines.length; i++) {
  const m = /^theorem (relation_[0-9a-z_]+) : (.+?) :=/.exec(lines[i]!)
  if (!m) continue
  const doc = /\/-- (.+?) meet at/.exec(lines[i - 1] ?? '')
  const families = doc ? doc[1]!.split(/,\s*|\s+and\s+/).map((s) => s.trim()).filter(Boolean) : []
  relations.push({ name: m[1]!, statement: m[2]!.trim(), families })
}
const out = `// GENERATED by scripts/gen-clay.ts from src/quantum/processing/unit/lean/Qpu/Clay.lean. Do not edit.
// The ${relations.length} Clay relations as the Lean file states them; the kernel accepted each by rfl. Each names the families of formulas it fuses (its doc comment), so the relations index by family — the Payload index of relations is this module, read by the sync.
export const CLAY_RELATIONS: readonly { name: string; statement: string; families: readonly string[] }[] = ${JSON.stringify(relations, null, 2)}
`
writeFileSync(join(ROOT, 'src/quantum/processing/clay-statements.ts'), out)
const byFamily: Record<string, number> = {}
for (const r of relations) for (const f of r.families) byFamily[f] = (byFamily[f] ?? 0) + 1
console.log(`gen-clay: ${relations.length} relations; families ${Object.entries(byFamily).map(([f, n]) => `${f}:${n}`).join(', ')}`)
