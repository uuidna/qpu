#!/usr/bin/env node
/**
 * THE WORDS OF EACH FAMILY, GENERATED FROM ITS OWN DOC COMMENT. A family's first doc comment names its domain ("of the
 * prime domain", "health", "aquaponics"). Those words are the family's search words for the public APIs, so a family
 * reaches the APIs its own comment names. The words are written as a constant, because a Worker has no filesystem.
 *
 *   npm run family:words        writes src/mcp/family-words.ts
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const FAMILIES = join(ROOT, 'src/families')
const OUT = join(ROOT, 'src/mcp/family-words.ts')

// words a doc comment uses for its own shape, not its domain
const STOP = new Set(['formula', 'formulas', 'exact', 'integer', 'integers', 'family', 'domain', 'with', 'from', 'that', 'this', 'each', 'with', 'their', 'there', 'where', 'which', 'when', 'over', 'into', 'about', 'family', 'families', 'value', 'values', 'hex', 'address', 'addresses', 'program', 'programs', 'unit', 'qpu', 'lean', 'theorem', 'theorems', 'proof', 'proofs', 'every', 'only', 'also', 'used', 'uses', 'these', 'those', 'have', 'been', 'being', 'then', 'than', 'such', 'more', 'most', 'some', 'many', 'make', 'made', 'does', 'done', 'data', 'reading', 'readings', 'source', 'sources', 'live', 'public', 'check', 'checks', 'checked'])

/** The first doc comment of a family module, as words of four letters or more, without the stop words. */
const wordsOf = (text: string): string[] => {
  const doc = text.match(/\/\*\*([\s\S]*?)\*\//)?.[1] ?? ''
  const words = doc.toLowerCase().split(/[^a-z]+/).filter((w) => w.length >= 4 && !STOP.has(w))
  return [...new Set(words)]
}

const families = readdirSync(FAMILIES).filter((f) => statSync(join(FAMILIES, f)).isDirectory()).sort()
const table: Record<string, string[]> = {}
for (const family of families) {
  const path = join(FAMILIES, family, 'index.ts')
  try {
    const words = wordsOf(readFileSync(path, 'utf8'))
    if (words.length) table[family] = words
  } catch {
    // a folder with no module is not a family
  }
}
writeFileSync(OUT, `// Generated by scripts/family-words.ts from each family's doc comment — regenerate, do not edit\nexport const FAMILY_WORDS: Record<string, readonly string[]> = ${JSON.stringify(table)}\n`)
console.log(`family words: ${Object.keys(table).length} families of ${families.length} folders carry words from their doc comment`)
