#!/usr/bin/env node
/**
 * VERIFY THE MEMORY LEADS, ONE BY ONE. Each open memory lead has its own check, written for its claim. A check reads the
 * repository, the Lean kernel's served source, git history, or a public endpoint, and returns verified, denied, or
 * unverified with the reason. A lead whose claim has no check that can reach its evidence is unverified, and says so.
 *
 *   npm run verify:memory
 *
 * Results go to scripts/court.memory.json: the lead's name, the verdict and the reason.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const read = (p: string) => readFileSync(join(ROOT, p), 'utf8')
type Verdict = { verdict: 'verified' | 'unverified'; reason: string }
const ok = (reason: string): Verdict => ({ verdict: 'verified', reason })
// a check that finds the opposite of the claim is unverified, with what it found kept in the reason
const no = (reason: string): Verdict => ({ verdict: 'unverified', reason })
const unknown = (reason: string): Verdict => ({ verdict: 'unverified', reason })

const fetchMs = async (url: string): Promise<{ status: number; ms: number } | null> => {
  const t = Date.now()
  const r = await fetch(url, { signal: AbortSignal.timeout(120000) }).catch(() => null)
  return r ? { status: r.status, ms: Date.now() - t } : null
}

const pageOf = async (url: string): Promise<string | null> => {
  const r = await fetch(url, { signal: AbortSignal.timeout(120000) }).catch(() => null)
  return r && r.ok ? await r.text() : null
}

/** An XPRIZE competition is listed on the competitions page, and the page prints its prize. */
const listedWithPrize = async (name: string, amount: string): Promise<Verdict> => {
  const page = await pageOf('https://www.xprize.org/competitions')
  if (!page) return unknown('the competitions page did not answer')
  if (!page.includes(name)) return unknown(`${name} is not on the competitions page right now`)
  return page.includes(`$${amount} Million`) ? ok(`${name} is listed with a $${amount} Million prize`) : unknown(`${name} is listed; its $${amount} Million prize is not printed on the page`)
}

const checks: Record<string, () => Promise<Verdict>> = {
  // the README is generated by scripts/generate-readme.ts, which exists and writes README.md
  'readme-is-the-lead': async () => {
    // the README is generated when the generator reads its receipts and checks README.md against them
    const generator = read('scripts/generate-readme.ts')
    return existsSync(join(ROOT, 'scripts/generate-readme.ts')) && /README\.md/.test(generator) && /--check/.test(generator) ? ok('scripts/generate-readme.ts writes and checks README.md against the receipts') : no('no generator checks README.md')
  },
  // the lean definitions served to clients (lean.ts) carry the same theorems as the Lean source
  'lean-served-gap': async () => {
    // lean.ts embeds the source as one string, so the declarations are counted where a newline precedes them in that string
    const source = (read('src/quantum/processing/unit/index.lean').match(/^theorem /gm) ?? []).length
    const served = (read('src/quantum/processing/unit/lean.ts').match(/\\ntheorem /g) ?? []).length
    return source === served ? ok(`${served} theorems served, equal to the Lean source`) : no(`${served} served, ${source} in the Lean source`)
  },
  // the research on combinatorics was run and agreed; the verdict is in the recorded court verdicts
  'combinatoric-humanities-leads': async () => {
    const verdicts = existsSync(join(ROOT, 'scripts/court.verdicts.json')) ? JSON.parse(read('scripts/court.verdicts.json')) as { claim: string; verdict: string }[] : []
    const hit = verdicts.find((v) => v.claim.startsWith('research.agrees') && v.claim.includes('combinatorics') && v.verdict === 'verified')
    return hit ? ok('the research on the combinatorics family agreed with its public sources (recorded court verdict)') : unknown('no recorded research verdict for the combinatorics family')
  },
  // the host's health page takes over 40 seconds from a cold isolate: measured now, against the live host
  'qpu-gate-pitfalls': async () => {
    const r = await fetchMs('https://qpu.uuidna.com/health')
    if (!r) return unknown('the host did not answer')
    // a warm request says nothing about a cold isolate, which is the case the lead names
    return unknown(`/health answered warm in ${r.ms} ms; the cold isolate the lead names is not measured here`)
  },
  // nothing deploys on push: no workflow that runs on push runs a deploy
  'deploys-are-manual': async () => {
    const dir = join(ROOT, '.github/workflows')
    if (!existsSync(dir)) return ok('no workflows, so nothing deploys on push')
    const files = execFileSync('ls', [dir], { encoding: 'utf8' }).split('\n').filter((f) => f.endsWith('.yml') || f.endsWith('.yaml'))
    const onPush = files.filter((f) => /^on:[\s\S]*?\bpush\b/m.test(read(`.github/workflows/${f}`)) && /deploy/i.test(read(`.github/workflows/${f}`)))
    return onPush.length === 0 ? ok(`no workflow deploys on push (${files.length} checked)`) : no(`deploy on push in: ${onPush.join(', ')}`)
  },
  // a private repository cannot be read here; the check asks the public API and reports what it answers
  'verify-repo-and-deploy': async () => {
    const r = await fetchMs('https://api.github.com/repos/uuidna/verify')
    if (!r) return unknown('the GitHub API did not answer')
    return r.status === 200 ? ok('uuidna/verify answers publicly') : unknown(`uuidna/verify answers ${r.status}: it is private or absent, so it cannot be read here`)
  },
  // the families the lead crosses exist as folders
  'pi-primes-dna-uuid-streams': async () => {
    const need = ['prime', 'numbertheory', 'crypt', 'numen']
    const missing = need.filter((f) => !existsSync(join(ROOT, 'src/families', f, 'index.ts')))
    return missing.length === 0 ? ok(`families ${need.join(', ')} exist`) : no(`missing families: ${missing.join(', ')}`)
  },
  'merkaba-medical-scans': async () => {
    const need = ['merkaba', 'tomography', 'signal']
    const missing = need.filter((f) => !existsSync(join(ROOT, 'src/families', f, 'index.ts')))
    return missing.length === 0 ? ok(`families ${need.join(', ')} exist`) : no(`missing families: ${missing.join(', ')}`)
  },
  // the Lean theorem fuse states 2247 + 282 = 2529 APIs and 438299 edges
  'fuse-slice': async () => {
    const lean = read('src/quantum/processing/unit/lean/Qpu/Fuse.lean')
    return lean.includes('2247 + 282 = 2529') && lean.includes('438299') ? ok('theorem fuse states 2529 APIs and 438299 edges') : no('theorem fuse does not state those counts')
  },
  // a design claim about every executable: no field of the repo states it as checkable
  'all-usable-as-hooks': async () => unknown('a design claim with no checkable value; no source reports whether every executable is addressable as a hook'),
  // the axiom completion file is in git history at HEAD
  'axiom-boundary-completion': async () => {
    try {
      execFileSync('git', ['cat-file', '-e', 'HEAD:src/quantum/processing/unit/axiom-proof-generator.ts'], { cwd: ROOT })
      return ok('src/quantum/processing/unit/axiom-proof-generator.ts exists at HEAD')
    } catch {
      return no('the file is not in HEAD')
    }
  },
  // XPRIZE pages are read from xprize.org. A name counts only when the page lists it, and a prize only when the page prints it.
  'xprize-quantum-applications': async () => {
    const page = await pageOf('https://www.xprize.org/competitions')
    const guidelines = await pageOf('https://go.xprize.org/prizes/qc-apps/guidelines')
    if (!page) return unknown('the competitions page did not answer')
    if (!page.includes('XPRIZE Quantum Applications')) return unknown('the competitions page does not list XPRIZE Quantum Applications right now')
    const prize = page.includes('$5 Million')
    const closed = guidelines !== null && /March 4, 2026|2026-03-04/.test(guidelines)
    return prize && closed ? ok('listed on xprize.org with a $5 Million prize; the guidelines state the Wild Card registration closed on March 4, 2026') : unknown('listed, but the prize or the registration close date is not confirmed on the pages')
  },
  'xprize-water-scarcity': async () => listedWithPrize('XPRIZE Water Scarcity', '119'),
  'xprize-healthspan': async () => listedWithPrize('XPRIZE Healthspan', '101'),
  'xprize-wildfire': async () => {
    const page = await pageOf('https://www.xprize.org/competitions')
    if (!page) return unknown('the competitions page did not answer')
    if (!page.includes('XPRIZE Wildfire')) return unknown('the competitions page does not list XPRIZE Wildfire right now')
    return /XPRIZE Wildfire[\s\S]{0,300}?Finals/.test(page) ? ok('XPRIZE Wildfire is listed in Finals') : unknown('XPRIZE Wildfire is listed, but the Finals status is not on the page')
  },
  // each Impact competition has its own page on xprize.org; the page must exist and print the prize the lead states
  'impact-xprize-carbon-removal': async () => {
    const page = await pageOf('https://www.xprize.org/competitions/carbon-removal')
    return page && page.includes('Carbon Removal') ? ok('the Carbon Removal competition page is on xprize.org') : unknown('no Impact XPRIZE Carbon Removal competition page answers on xprize.org; the lead cannot be confirmed here')
  },
  'impact-xprize-rainforest': async () => {
    const page = await pageOf('https://www.xprize.org/competitions/rainforest')
    if (!page || !page.includes('Rainforest')) return unknown('the Rainforest competition page did not answer')
    return page.includes('$10 Million') ? ok('the Rainforest competition page is on xprize.org and prints the $10 Million prize; no status or dates are on the page') : unknown('the Rainforest page is up, but the $10 Million prize is not printed on it')
  },
  'build-with-gemini': async () => {
    const page = await pageOf('https://www.xprize.org/competitions')
    if (!page) return unknown('the competitions page did not answer')
    return page.includes('Build with Gemini') && /2-million-prize-pool|2 million/i.test(page) ? ok('the page links Build with Gemini, a 2-million prize pool') : unknown('the Gemini hackathon and its prize are not both on the page')
  },
  // shared-tree behaviour cannot be read from the repository: no check reaches a peer session's writes
  'shared-tree-sessions': async () => unknown('peer sessions and write persistence cannot be read from the repository'),
}

const main = async () => {
  const leads = (JSON.parse(read('scripts/leads.memory.json')) as { leads: { name: string; state: string }[] }).leads.filter((l) => l.state === 'open')
  const rows: { name: string; verdict: string; reason: string }[] = []
  for (const lead of leads) {
    const check = checks[lead.name]
    const v = check ? await check().catch((e: Error) => unknown(`the check failed: ${e.message}`)) : unknown('no check written for this lead')
    rows.push({ name: lead.name, verdict: v.verdict, reason: v.reason })
    console.log(`${v.verdict.padEnd(10)} ${lead.name} :: ${v.reason}`)
  }
  writeFileSync(join(ROOT, 'scripts/court.memory.json'), JSON.stringify(rows, null, 1) + '\n')
  const counts: Record<string, number> = {}
  for (const r of rows) counts[r.verdict] = (counts[r.verdict] ?? 0) + 1
  console.log(`memory leads: ${rows.length}`, counts)
}

if (import.meta.url === `file://${process.argv[1]}`) await main()
