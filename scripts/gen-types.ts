#!/usr/bin/env node
/**
 * Generates scripts/types.gen.ts from the shapes in scripts/types.hex.ts: one TypeScript interface per shape, and a
 * TYPE_UUID map that gives each type the content UUID of its canonical shape (contentUuidOf). The output is
 * generated; edit the shapes, not the output.
 *
 *   npx tsx scripts/gen-types.ts            write types.gen.ts
 *   npx tsx scripts/gen-types.ts --check    exit 1 if types.gen.ts is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { TYPES } from './types.hex.js'
// the content address is the repository's own: a JSON value's canonical text, hashed to a UUID
import { contentUuidOf } from '../dist/quantum/processing/unit/index.js'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, 'types.gen.ts')
const PRIMITIVES = new Set(['string', 'number', 'boolean', 'unknown'])

const typeOf = (name: string): string => {
  if (name.endsWith('[]')) return `${typeOf(name.slice(0, -2))}[]`
  if (name === 'Dict') return 'Dict'
  if (name === 'Map') return 'Record<string, unknown>'
  if (PRIMITIVES.has(name)) return name
  if (!(name in TYPES)) throw new Error(`gen-types: ${name} is not a primitive or a shape in types.hex.ts`)
  return name
}

const fieldOf = (key: string, type: string): string => {
  const optional = key.endsWith('?')
  const bare = optional ? key.slice(0, -1) : key
  const safe = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(bare) ? bare : `'${bare}'`
  return `${safe}${optional ? '?' : ''}: ${typeOf(type)}`
}

/** The generated source, from the shapes alone. Pure: the drift check compares it with the file on disk. */
export const renderTypes = (): string => {
  const names = Object.keys(TYPES)
  const interfaces = names.map((name) => {
    const fields = Object.entries(TYPES[name]!).map(([key, type]) => `  ${fieldOf(key, type)}`)
    return `export interface ${name} {\n${fields.join('\n')}\n}`
  })
  const uuids = names.map((name) => `  ${name}: '${contentUuidOf(TYPES[name])}',`)
  return [
    '// GENERATED by scripts/gen-types.ts from scripts/types.hex.ts. Do not edit; edit the shapes and rerun the generator.',
    '',
    'export type Dict = Record<string, string>',
    '',
    interfaces.join('\n\n'),
    '',
    '/** The content UUID of each type\'s canonical shape. Changing a field changes its UUID. */',
    'export const TYPE_UUID = {',
    ...uuids,
    '} as const',
    '',
  ].join('\n')
}

const invoked = process.argv[1]?.endsWith('gen-types.ts') === true
if (invoked) {
  const text = renderTypes()
  if (process.argv.includes('--check')) {
    const held = (() => { try { return readFileSync(OUT, 'utf8') } catch { return null } })()
    if (held !== text) {
      console.error('gen-types: types.gen.ts is out of date — run `npx tsx scripts/gen-types.ts`')
      process.exit(1)
    }
    console.log('gen-types: types.gen.ts is current')
  } else {
    writeFileSync(OUT, text)
    console.log(`gen-types: wrote ${OUT}`)
  }
}
