/** A page's frontmatter: `key: value` lines between two `---` fences. */
const frontmatterOf = (text: string): Record<string, string> => {
  const m = /^---\n([\s\S]*?)\n---/.exec(text)
  if (!m) return {}
  return Object.fromEntries(m[1]!.split('\n').map((line) => line.split(':')).filter((p) => p.length >= 2).map(([k, ...v]) => [k!.trim(), v.join(':').trim()]))
}

const pages = readdirSync(DOCS)
  .filter((f) => f.endsWith('.md'))
  .map((f) => {
    const fm = frontmatterOf(readFileSync(join(DOCS, f), 'utf8'))
    const route = f === 'index.md' ? '/' : `/${f.replace(/\.md$/, '')}`
    return { file: f, route, title: fm.title ?? f, order: Number(fm.order ?? 99), nav: fm.nav !== 'false' }
  })
  .sort((a, b) => a.order - b.order || a.file.localeCompare(b.file))

const nav = pages.filter((p) => p.nav).map((p) => ({ text: p.title, link: p.route }))
const sidebar = [
  { text: 'Pages', items: pages.filter((p) => p.route !== '/').map((p) => ({ text: p.title, link: p.route })) },
  ...toolboxes.map((b) => ({ text: `Toolbox ${b.name}`, items: b.tools.map((t) => ({ text: t.name, link: `/mcp#${t.name}` })) })),
]

