// Generates the VitePress site from the code it documents: the MCP reference page and the static manifest come from the
// handler's own tools/list, and the config's nav and sidebar come from the pages' frontmatter and from the tools. Nothing
// here is typed by hand except the pages themselves. Run as `npm run docs:gen`; the site never reads a hand-written config.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { handle } from '../src/quantum/mcp.js'
import { cssOf } from '../src/quantum/theme.js'
import { LEADS } from '../src/quantum/leads.js'

const ROOT = process.cwd()
const DOCS = join(ROOT, 'docs')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')) as { name: string; description: string; homepage?: string; repository?: string }

const tools = (() => {
  const reply = handle({ jsonrpc: '2.0', id: 1, method: 'tools/list' })
  if (!('result' in reply)) throw new Error(`tools/list failed: ${JSON.stringify(reply)}`)
  return (reply.result as { tools: { name: string; description: string; inputSchema: object }[] }).tools
})()

/** The mcp.md reference page: one section per tool, each heading an anchor the sidebar links to. */
const mcpPage = [
  '---',
  'title: MCP',
  'order: 40',
  '---',
  '',
  '# MCP tools',
  '',
  'The handler in `src/quantum/mcp.ts` answers `initialize`, `tools/list` and `tools/call` as JSON-RPC 2.0. Its tools take typed',
  'POST parameters described by the JSON Schema below, and they compile the circuit they describe on each call.',
  '',
  ...tools.flatMap((t) => [
    `## ${t.name}`,
    '',
    t.description,
    '',
    '```json',
    JSON.stringify(t.inputSchema, null, 2),
    '```',
    '',
  ]),
].join('\n')
writeFileSync(join(DOCS, 'mcp.md'), mcpPage)

mkdirSync(join(DOCS, 'public'), { recursive: true })
writeFileSync(join(DOCS, 'public', 'a432.css'), cssOf())
writeFileSync(join(DOCS, 'public', 'mcp.json'), JSON.stringify({ name: pkg.name, protocol: 'JSON-RPC 2.0', tools }, null, 2) + '\n')

/** The leads page: every lead on quantumai.google with its status and the tool that serves it, from the lead registry. */
const leadsPage = [
  '---',
  'title: Leads',
  'order: 45',
  '---',
  '',
  '# Leads',
  '',
  'Every lead on quantumai.google and its linked PDF, with its status and the MCP tool that serves it. The `leads` tool returns the same registry.',
  '',
  '| Lead | Status | Tool | Statement | Reason |',
  '| --- | --- | --- | --- | --- |',
  ...LEADS.map((l) => `| \`${l.id}\` | ${l.status} | ${l.tool ?? '—'} | ${l.statement} | ${l.reason ?? ''} |`),
  '',
].join('\n')
writeFileSync(join(DOCS, 'leads.md'), leadsPage)

/** A page's frontmatter: `key: value` lines between two `---` fences. */
const frontmatterOf = (text: string): Record<string, string> => {
  const m = /^---\n([\s\S]*?)\n---/.exec(text)
  if (!m) return {}
  return Object.fromEntries(m[1]!.split('\n').map((line) => line.split(':')).filter((p) => p.length >= 2).map(([k, ...v]) => [k!.trim(), v.join(':').trim()]))
}

const pages = readdirSync(DOCS)
  .filter((f) => f.endsWith('.md'))
  .map((f) => {
    const fm = frontmatterOf(readFileSync(join(DOCS, f), 'utf8'))
    const route = f === 'index.md' ? '/' : `/${f.replace(/\.md$/, '')}`
    return { file: f, route, title: fm.title ?? f, order: Number(fm.order ?? 99), nav: fm.nav !== 'false' }
  })
  .sort((a, b) => a.order - b.order || a.file.localeCompare(b.file))

const nav = pages.filter((p) => p.nav).map((p) => ({ text: p.title, link: p.route }))
const sidebar = [
  { text: 'Pages', items: pages.filter((p) => p.route !== '/').map((p) => ({ text: p.title, link: p.route })) },
  { text: 'MCP tools', items: tools.map((t) => ({ text: t.name, link: `/mcp#${t.name}` })) },
]

const config = `// GENERATED by scripts/gen-docs.ts from package.json, the pages in docs/ and the tools in src/quantum/mcp.ts. Do not edit.
import { defineConfig } from 'vitepress'

export default defineConfig({
  title: ${JSON.stringify(pkg.name)},
  description: ${JSON.stringify(pkg.description)},
  cleanUrls: true,
  head: [['link', { rel: 'stylesheet', href: '/uuidna.css' }], ['link', { rel: 'stylesheet', href: '/a432.css' }], ['link', { rel: 'license', href: 'https://uuidna.com/license' }], ['meta', { name: 'license', content: 'CC-BY-NC-ND-4.0' }], ['meta', { name: 'copyright', content: '© 2025 Tsvetan Rouschev (ceccec@psg.bg)' }], ['meta', { property: 'uuidna:rights', content: '459a7ef3-7a8b-8d8e-893a-099292addcd5' }], ['meta', { property: 'uuidna:canonical', content: 'https://uuidna.com' }]],
  themeConfig: {
    footer: { message: 'CC-BY-NC-ND-4.0 — attribute the author, no derivatives, commercial use of the QPU framework, over UUID or by any other means, by licence (ceccec@psg.bg); the a432 harmonic default is free to all under attribution.', copyright: '© Tsvetan Rouschev · https://orcid.org/0009-0000-7312-9778' },
    nav: ${JSON.stringify(nav, null, 2).replace(/\n/g, '\n    ')},
    sidebar: ${JSON.stringify(sidebar, null, 2).replace(/\n/g, '\n    ')},
  },
})
`
mkdirSync(join(DOCS, '.vitepress'), { recursive: true })
writeFileSync(join(DOCS, '.vitepress', 'config.mts'), config)
console.log(`docs: ${pages.length} pages, ${tools.length} tools, config written`)
