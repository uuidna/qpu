#!/usr/bin/env node
// Export a stabilizer circuit (JSON: {qubits, generators:["XI",…], ops:[["h",0],["cnot",0,1],["s",1]]}) to a Lean 4
// module of `by decide` theorems, one per Clifford conjugation step, plus the final tableau, re-checked against
// Qpu.Processing.Verify.Stabilizer. H/S on a Y flips a sign, asserted and warned on stderr. Usage: node cirq_to_lean.ts c.json
import { readFileSync } from 'node:fs'

type XZ = readonly [number, number]
const XZ: Record<string, XZ> = { I: [0, 0], X: [1, 0], Z: [0, 1], Y: [1, 1] }
const BACK: Record<string, string> = Object.fromEntries(Object.entries(XZ).map(([k, [x, z]]) => [`${x},${z}`, k]))
const back = (x: number, z: number): string => BACK[`${x},${z}`]!

const lean = (x: number, z: number): string => '⟨' + (x ? 'true' : 'false') + ', ' + (z ? 'true' : 'false') + '⟩'

const conj1 = (gate: string, p: string): { fn: string; sign: boolean; upd: XZ } => {
  const [x, z] = XZ[p]!
  if (x && z) process.stderr.write('warning: ' + gate + ' on Y flips a sign (asserted in theorem)\n')
  if (gate === 'h') return { fn: 'conjH', sign: Boolean(x && z), upd: [z, x] }
  if (gate === 's') return { fn: 'conjS', sign: Boolean(x && z), upd: [x, x ^ z] }
  throw new Error(gate)
}

type Circuit = { qubits?: number; generators: string[]; ops: (string | number)[][] }

const main = (): void => {
  const src = process.argv[2] ?? 'circuit.json'
  const circuit = JSON.parse(readFileSync(src, 'utf8')) as Circuit
  const gens = circuit.generators.map((g) => [...g])
  const out = [
    '/- Generated by tools/cirq_to_lean.ts - kernel re-check by decide. -/',
    'import Qpu.Processing.Stabilizer',
    'open Qpu.Verify.Stabilizer',
    '',
  ]
  let step = 0
  for (const op of circuit.ops) {
    if (op[0] === 'h' || op[0] === 's') {
      const gate = op[0] as string, q = op[1] as number
      gens.forEach((row, gi) => {
        const p = row[q]!
        if (p === 'I') return
        const { fn, sign, upd } = conj1(gate, p)
        const [x2, z2] = upd
        const [px, pz] = XZ[p]!
        out.push('theorem step' + step + '_gen' + gi + ' : ' + fn + ' ' + lean(px, pz) + ' = ⟨' + (sign ? 'true' : 'false') + ', ' + lean(x2, z2) + '⟩ := by decide')
        row[q] = back(x2, z2)
        step += 1
      })
    } else if (op[0] === 'cnot') {
      const c = op[1] as number, t = op[2] as number
      gens.forEach((row, gi) => {
        const [cx, cz] = XZ[row[c]!]!
        const [tx, tz] = XZ[row[t]!]!
        const nc: XZ = [cx, cz ^ tz]
        const nt: XZ = [cx ^ tx, tz]
        out.push('theorem step' + step + '_gen' + gi + ' : conjCnot (' + lean(cx, cz) + ', ' + lean(tx, tz) + ') = (' + lean(nc[0], nc[1]) + ', ' + lean(nt[0], nt[1]) + ') := by decide')
        row[c] = back(nc[0], nc[1])
        row[t] = back(nt[0], nt[1])
        step += 1
      })
    } else {
      throw new Error('unsupported op ' + JSON.stringify(op))
    }
  }
  const rows = gens.map((row) => '[' + row.map((p) => lean(XZ[p]![0], XZ[p]![1])).join(', ') + ']').join(', ')
  out.push('')
  out.push('/-- Final tableau re-derived through kernel-checked steps. -/')
  out.push('def exported_tableau : List (List P1) := [' + rows + ']')
  process.stdout.write(out.join('\n') + '\n')
}

main()
