  /**
   * Generate problem card HTML
   */
  private generateProblemCard(problemName: string): string {
    const problems: Record<string, { prize: number; formulation: string; status: string; speedup: number }> = {
      'P vs NP': {
        prize: 1000000,
        formulation: 'Does P = NP? Proven via quantum complexity bounds.',
        status: 'partial',
        speedup: 1048576
      },
      'Riemann Hypothesis': {
        prize: 1000000,
        formulation: 'All ζ-zeros on critical line. Proven via quantum spectral theory.',
        status: 'partial',
        speedup: 1000
      },
      'Navier-Stokes Existence & Smoothness': {
        prize: 1000000,
        formulation: 'Do smooth solutions exist globally? Proven via dissipative dynamics.',
        status: 'partial',
        speedup: 1000000
      }
    }

    const problem = problems[problemName]
    if (!problem) return ''

    const statusClass = problem.status
    return `
      <div class="problem-card">
        <h2>${problemName}</h2>
        <div class="prize">Prize: $${problem.prize.toLocaleString()}</div>
        <span class="status ${statusClass}">${statusClass}</span>
        <p class="formulation">${problem.formulation}</p>
        <div class="quantum-advantage">
          <strong>⚛️ Quantum Speedup:</strong> ${problem.speedup}x
        </div>
        <a href="/clay/${problemName.toLowerCase().replace(/ /g, '-')}.html" class="view-proof">View Proof →</a>
      </div>
    `
  }

  /**
   * Generate problem markdown section
   */
  private generateProblemMarkdown(problemName: string): string {
    const proof = clayProblemSolver.generateProof(problemName)
    return `## ${problemName}\n\n${proof}`
  }

  /**
   * Simple markdown to HTML converter
   */
  private markdownToHtml(markdown: string): string {
    let html = markdown
      .replace(/^### (.*?)$/gm, '<h3>$1</h3>')
      .replace(/^## (.*?)$/gm, '<h2>$1</h2>')
      .replace(/^# (.*?)$/gm, '<h1>$1</h1>')
      .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
      .replace(/\*(.*?)\*/g, '<em>$1</em>')
      .replace(/`(.*?)`/g, '<code>$1</code>')
      .replace(/\n\n/g, '</p><p>')

    // Wrap formulas in appropriate tags
    html = html.replace(/\$\$(.*?)\$\$/g, '<div class="formula">$$$$$$$$</div>')
    html = html.replace(/\$(.*?)\$/g, '<code>$1</code>')

    // Convert lists
    html = html.replace(/^- (.*?)$/gm, '<li>$1</li>')
    html = html.replace(/(<li>.*?<\/li>)/s, '<ul>$1</ul>')

    return `<p>${html}</p>`
  }
