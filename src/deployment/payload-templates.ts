/**
 * Payload Templates for 4-Mode Deployment
 * Browser / Standalone / Docker / Kubernetes
 * Each mode fully specified, formula-derived, zero-config
 */

export interface PayloadTemplate {
  mode: 'browser' | 'standalone' | 'docker' | 'kubernetes' | 'cloudflare'
  version: string
  spec: Record<string, unknown>
  hardware: HardwareTarget
  optimization: OptimizationConfig
  deployment: DeploymentConfig
}

export interface HardwareTarget {
  cpu: { cores: number; freq: number; cache: string }
  memory: { gb: number; type: string }
  network: { bw: string; latency: string }
  storage: { ssd: string; type: string }
  accelerators?: string[]
}

export interface OptimizationConfig {
  cpu: { ipc: number; frequency: number; powerGating: boolean }
  memory: { prefetch: boolean; compression: number; cacheSize: number }
  network: { routing: string; linkGating: boolean }
  power: { vrm: number; thermalTarget: number }
}

export interface DeploymentConfig {
  instances: number
  scaling: { min: number; max: number; target: number }
  monitoring: boolean
  selfHealing: boolean
  autonomousOptimization: boolean
}

/** What an image of the unit is made of, read from package.json and the unit rather than written into a template:
 *  the package (name, version, licence, author, repository), the Node line its engines field names, the port the boot
 *  listens on and the flags the boot answers (--health for the container, --prove for the boot's own receipt). */
export type ImageApp = {
  name: string
  version: string
  license: string
  author: string
  repository: string
  homepage: string
  node: number
  port: number
  boot: string
  health: string
  prove: string
  /** files the image carries beside dist and node_modules */
  ship: string[]
  /** the registry path an orchestrator pulls (ghcr.io/uuidna/qpu) */
  image: string
}

