/** The Dockerfile: a build stage that compiles (the version lock is the repository's gate, git and npm being outside the
 *  image), a runtime stage with only dist, production modules and what the package ships, run as its own user behind
 *  dumb-init at the path Alpine installs it, health being the boot's own answer. */
export const dockerfileOf = (a: ImageApp = IMAGE_DEFAULT): string => `# Generated by PayloadTemplates.dockerPayload from package.json and the unit — regenerate, do not edit
# Builds on arm64 and amd64: docker buildx build --platform linux/arm64,linux/amd64 -t ${a.image}:${a.version} .

FROM node:${a.node}-alpine AS build
WORKDIR /qpu
RUN apk add --no-cache python3 make g++
COPY package.json package-lock.json ./
# no lifecycle scripts: prepare would compile before src/ is copied, and the compile step follows
RUN npm ci --ignore-scripts
COPY tsconfig.json ./
COPY src/ ./src/
# compile only: the version lock (git history, npm registry) gates every commit and CI run
RUN npx tsc -p tsconfig.json && npm prune --omit=dev

FROM node:${a.node}-alpine
WORKDIR /qpu
ENV NODE_ENV=production PORT=${a.port}
RUN apk add --no-cache ca-certificates dumb-init
COPY --from=build /qpu/package.json /qpu/package-lock.json ./
COPY --from=build /qpu/dist ./dist
COPY --from=build /qpu/node_modules ./node_modules
COPY ${a.ship.join(' ')} ./
COPY src/quantum/processing/unit/index.lean ./src/quantum/processing/unit/
RUN addgroup -g 1001 -S qpu && adduser -S qpu -u 1001
USER qpu
EXPOSE ${a.port}
HEALTHCHECK --interval=60s --timeout=30s --start-period=10s --retries=3 CMD node ${a.boot} ${a.health} || exit 1
# Alpine installs dumb-init under /usr/bin
ENTRYPOINT ["/usr/bin/dumb-init", "--"]
CMD ["node", "${a.boot}"]

LABEL org.opencontainers.image.title="${a.name}" \
      org.opencontainers.image.version="${a.version}" \
      org.opencontainers.image.authors="${a.author}" \
      org.opencontainers.image.url="${a.homepage}" \
      org.opencontainers.image.source="${a.repository}" \
      org.opencontainers.image.licenses="${a.license}" \
      org.opencontainers.image.base.name="docker.io/library/node:${a.node}-alpine"
`

/** docker-compose: the one service, built from the Dockerfile beside it, its port published as the boot listens. */
