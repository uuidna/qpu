#!/usr/bin/env python3
"""Export a small stabilizer circuit to a kernel-decidable Lean 4 module.

Reads a JSON circuit:
  {"qubits": 2,
   "generators": ["XI", "IZ"],
   "ops": [["h", 0], ["cnot", 0, 1], ["s", 1]]}

Writes a Lean file where every conjugation step is re-proved by the kernel
(`by decide`) against the rules in `Qpu.Processing.Verify.Stabilizer`, plus the final
tableau as Lean data.

Limitations: tracks the symplectic (x, z) tableau; H/S on a Y flips a sign
that is asserted in the theorem but flagged as a stderr warning. Intended
for CI pre-flight of small Clifford circuits, not Stim-scale simulation.

Usage: python3 cirq_to_lean.py circuit.json > Generated.lean
"""
import json
import sys

XZ = {"I": (0, 0), "X": (1, 0), "Z": (0, 1), "Y": (1, 1)}
BACK = {v: k for k, v in XZ.items()}


def lean(x, z):
    return "\u27e8" + ("true" if x else "false") + ", " + ("true" if z else "false") + "\u27e9"


def conj1(gate, p):
    """One-qubit Clifford conjugation as a symplectic update."""
    x, z = XZ[p]
    if x and z:
        print("warning: " + gate + " on Y flips a sign (asserted in theorem)", file=sys.stderr)
    if gate == "h":
        return "conjH", bool(x and z), (z, x)
    if gate == "s":
        return "conjS", bool(x and z), (x, x ^ z)
    raise ValueError(gate)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "circuit.json"
    circuit = json.load(open(src))
    gens = [list(g) for g in circuit["generators"]]
    out = ["/- Generated by tools/cirq_to_lean.py - kernel re-check by decide. -/",
           "import Qpu.Processing.Verify.Stabilizer",
           "open Qpu.Verify.Stabilizer",
           ""]
    step = 0
    for op in circuit["ops"]:
        if op[0] in ("h", "s"):
            gate, q = op[0], op[1]
            for gi, row in enumerate(gens):
                p = row[q]
                if p == "I":
                    continue
                fn, sign, upd = conj1(gate, p)
                x2, z2 = upd
                out.append(
                    "theorem step" + str(step) + "_gen" + str(gi) + " : " + fn + " " +
                    lean(*XZ[p]) + " = \u27e8" + ("true" if sign else "false") + ", " +
                    lean(x2, z2) + "\u27e9 := by decide")
                row[q] = BACK[(x2, z2)]
                step += 1
        elif op[0] == "cnot":
            c, t = op[1], op[2]
            for gi, row in enumerate(gens):
                cx, cz = XZ[row[c]]
                tx, tz = XZ[row[t]]
                nc = (cx, cz ^ tz)
                nt = (cx ^ tx, tz)
                out.append(
                    "theorem step" + str(step) + "_gen" + str(gi) + " : conjCnot (" +
                    lean(cx, cz) + ", " + lean(tx, tz) + ") = (" +
                    lean(*nc) + ", " + lean(*nt) + ") := by decide")
                row[c], row[t] = BACK[nc], BACK[nt]
                step += 1
        else:
            raise ValueError("unsupported op " + str(op))
    rows = ", ".join("[" + ", ".join(lean(*XZ[p]) for p in row) + "]" for row in gens)
    out.append("")
    out.append("/-- Final tableau re-derived through kernel-checked steps. -/")
    out.append("def exported_tableau : List (List P1) := [" + rows + "]")
    print("\n".join(out))


if __name__ == "__main__":
    main()
