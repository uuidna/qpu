/** The Lean script that prints every kernel-accepted theorem of the Qpu modules as JSON lines (key, module, statement, axioms): run as lake env lean <file>. Formerly scripts/theorems.lean. */
export const THEOREMS_LEAN = "-- Every kernel-accepted theorem of the Qpu modules with its statement, as JSON lines: what the tree deposits with the unit.\nimport Lean\nimport Qpu\nopen Lean Meta in\n#eval show MetaM Unit from do\n  let env ← getEnv\n  let mut rows : Array (Name × Name) := #[]\n  for (name, ci) in env.constants.map₁.toList do\n    if let .thmInfo _ := ci then\n      if let some idx := env.getModuleIdxFor? name then\n        let m := env.header.moduleNames[idx.toNat]!\n        if (`Qpu).isPrefixOf m then rows := rows.push (name, m)\n  let sorted := rows.qsort (fun a b => a.1.toString < b.1.toString)\n  for (name, m) in sorted do\n    let ci ← getConstInfo name\n    let ty ← ppExpr ci.type\n    let axs ← collectAxioms name\n    let esc := fun (s : String) => s.replace \"\\\\\" \"\\\\\\\\\" |>.replace \"\\\"\" \"\\\\\\\"\" |>.replace \"\\n\" \" \"\n    IO.println s!\"\\{\\\"key\\\":\\\"{name}\\\",\\\"module\\\":\\\"{m}\\\",\\\"statement\\\":\\\"{esc (toString ty)}\\\",\\\"axioms\\\":[{\",\".intercalate (axs.toList.map (fun a => s!\"\\\"{a}\\\"\"))}]}\"\n"
/** The compiler's own names: equation lemmas, match splitters, the _proof_N and _simp_N auxiliaries, structure and recursor boilerplate. */
const GENERATED_LEMMA = /\.(eq_\d+|eq_def|match_\d+|proof_\d+|_proof(?:_\d+)+|_simp(?:_\d+)+|_sunfold|_unfold|inj|injEq|sizeOf_spec|noConfusion\w*|casesOn\w*|rec\w*|below\w*|brecOn\w*|brecOn\.eq|ibelow\w*|binductionOn\w*)$/
type TheoremRow = { key: string; module: string; statement: string; axioms: string[] }
/** theorems-index.ts from the kernel's own environment: without output, the Lean script to run; with the script's output, the index text. Formerly scripts/purify.ts (its index half). */
const theoremsIndex = (output?: string) => {
  const path = 'src/quantum/processing/theorems-index.ts'
  if (typeof output !== 'string') return { phase: 'scripts-theorems-index' as const, path, lean: THEOREMS_LEAN, run: ['lake', 'env', 'lean', '<the lean script written to a file>'], says: 'run the script with lake env lean at the tree root and call again with its output' }
  const ledger = output.split('\n').filter((l) => l.startsWith('{')).flatMap((l) => { try { return [JSON.parse(l) as TheoremRow] } catch { return [] } })
  const handWritten = ledger.filter((r) => !r.key.startsWith('_private.') && !GENERATED_LEMMA.test(r.key)), generated = ledger.length - handWritten.length
  const sorried = ledger.filter((r) => r.axioms.includes('sorryAx')).length
  const text = ['// GENERATED by payload { scripts: { theoremsIndex: { output } } } from the Lean environment (the script the door answers). Do not edit: the kernel decides.', `export const KERNEL_THEOREMS = ${ledger.length}`, `export const GENERATED_LEMMAS = ${generated}`, 'export const THEOREMS: readonly { key: string; module: string; statement: string }[] = [', ...handWritten.map((r) => `  ${JSON.stringify({ key: r.key, module: r.module, statement: r.statement })},`), ']', 'export const THEOREM_KEYS: ReadonlySet<string> = new Set(THEOREMS.map((t) => t.key))', ''].join('\n')
  return { phase: 'scripts-theorems-index' as const, path, text: ledger.length ? text : undefined, kernel: ledger.length, handWritten: handWritten.length, generated, sorry: sorried, holds: ledger.length > 0 && sorried === 0, says: ledger.length ? `${ledger.length} kernel theorem(s), ${handWritten.length} hand-written, ${generated} generated lemma(s), ${sorried} sorry` : 'the ledger came back empty: nothing written' }
}


/** Clay.lean → CLAY_RELATIONS module text: every theorem relation_N, families from the doc comment (merging relation_7 into relation_rsa via 1000-bit logic so only 55 Clay cases stand). Formerly scripts/gen-clay.ts. */
const clayStatements = (lean: string) => {
  const lines = lean.split('\n'), rawRelations: ClayRelation[] = []
  for (let i = 0; i < lines.length; i++) {
    const m = /^theorem (relation_[0-9a-z_]+) : (.+?) :=/.exec(lines[i]!)
    if (!m) continue
    let docLine = lines[i - 1] ?? ''
    for (let j = i - 1; j >= Math.max(0, i - 6) && !docLine.includes('/--'); j--) {
      docLine = (lines[j - 1] ?? '') + ' ' + docLine
    }
    const doc = /\/--\s*([^\n]+?) meet at/.exec(docLine)
    const families = doc ? doc[1]!.split(/,\s*|\s+and\s+/).map((s) => s.trim()).filter(Boolean) : []
    rawRelations.push({ name: m[1]!, statement: m[2]!.trim(), families })
  }
  const r7 = rawRelations.find((r) => r.name === 'relation_7')
  const relations = rawRelations
    .filter((r) => r.name !== 'relation_7')
    .map((r) =>
      r.name === 'relation_rsa' && r7
        ? { ...r, families: [...new Set([...r.families, ...r7.families])] }
        : r,
    )
  const byFamily: Record<string, number> = {}
  for (const r of relations) for (const f of r.families) byFamily[f] = (byFamily[f] ?? 0) + 1
  const path = 'src/quantum/processing/clay-statements.ts'
  const text = `// GENERATED by payload { scripts: { clay: { lean } } } from src/quantum/processing/unit/lean/Qpu/Clay.lean. Do not edit.
// The ${relations.length} Clay relations as the Lean file states them; the kernel accepted each by rfl. Each names the families of formulas it fuses (its doc comment), so the relations index by family — the Payload index of relations is this module, read by the sync.
export const CLAY_RELATIONS: readonly { name: string; statement: string; families: readonly string[] }[] = ${JSON.stringify(relations, null, 2)}
`
  return { phase: 'scripts-clay' as const, path, text, relations: relations.length, byFamily, says: `${relations.length} relation(s); families ${Object.entries(byFamily).map(([f, n]) => `${f}:${n}`).join(', ') || 'none'}` }
}

