/** BLUEPRINT.md from the blueprint's Lean: each module's doc (its frontmatter names the component) and, from the kernel's index, every
 *  theorem of that module and every theorem its doc names, with its statement. Nothing in the page is typed. */
const blueprint = (lean: Readonly<Record<string, string>>) => {
  const path = 'src/quantum/BLUEPRINT.md', cell = (t: string) => t.replace(/\s+/g, ' ').replace(/\|/g, '\\|')
  const modules = Object.values(lean).flatMap((text) => {
    const doc = /\/-!\s*#\s*(\S+)\n---\ncomponent: ([^\n]+)\n---\n([\s\S]*?)-\//.exec(text)
    return doc ? [{ module: doc[1]!, component: doc[2]!.trim(), prose: doc[3]!.trim() }] : []
  })
  const sections = modules.map((m) => {
    const named = [...m.prose.matchAll(/`([A-Za-z_][\w.]*)`/g)].map((x) => x[1]!)
    // a name with a segment opening on _ is the compiler's own auxiliary lemma, never a component's theorem
    const rows = THEOREMS.filter((t) => !/(^|\.)_/.test(t.key) && (t.module === m.module || named.includes(t.key)))
    return [`## ${m.component}`, '', `\`${m.module}\`. ${m.prose.replace(/\n/g, ' ')}`, '', ...(rows.length ? ['| Theorem | Module | Statement |', '|---|---|---|', ...rows.map((t) => `| \`${t.key}\` | ${t.module} | \`${cell(t.statement)}\` |`)] : []), ''].join('\n')
  })
  const text = ['<!-- GENERATED by payload { scripts: { blueprint } } from the blueprint\'s Lean and the kernel\'s theorem index. Do not edit: Lean decides. -->', '', '# Blueprint of the qpu quantum computer design', '', ...sections].join('\n')
  const theorems = sections.join('\n').split('\n').filter((l) => l.startsWith('| `')).length
  return { phase: 'scripts-blueprint' as const, path, text, modules: modules.length, theorems, says: `${theorems} theorem(s) across ${modules.length} component(s), from the Lean and the kernel's index` }
}

