test('a follow computes the ISO wave at 432 Hz and signals the 8 coins', () => {
  const wave = followWave([{ id: 'iso-16', statement: 'ISO 16 states 440 Hz' }])
  assert.equal(wave.holds, true)
  assert.equal(wave.hz, 432)
  assert.equal(wave.stated, 440)
  assert.equal(wave.difference, 8)
  assert.equal(wave.ratio.low, 54)
  assert.equal(wave.ratio.high, 55)
  assert.equal(wave.ratio.unit, 1)
  assert.equal(wave.proton.integer, 1836)
  assert.equal(wave.proton.scale, 34)
  assert.equal(wave.proton.low, 1836)
  assert.equal(wave.proton.high, 1870)
  assert.equal(wave.proton.drift, 34)
  assert.equal(wave.proton.relative.numerator * wave.proton.integer, wave.proton.drift * wave.proton.relative.denominator)
  assert.equal(wave.proton.published.replaced, false)
  assert.equal(wave.proton.published.mantissa, '167262192595')
  assert.equal(wave.waves.terms, QUANTUM_TERMS.length)
  assert.equal(wave.waves.rows.every((row) => row.hz === 432), true)
  assert.equal(wave.textbooks.exposed, TEXTBOOK_THEOREMS.length)
  assert.equal(wave.textbooks.immediate, true)
  assert.equal(wave.textbooks.solved, TEXTBOOK_THEOREMS.length)
  assert.equal(wave.problems.rows.every((row) => row.solved && row.by === 'textbook_tuning_ratio'), true)
  assert.equal(wave.signal.deducted, 8)
  assert.equal(wave.signal.added, 8)
  assert.equal(wave.signal.net, 0)
  assert.equal(wave.signal.line.debit, 'pitch:440')
  assert.equal(wave.signal.line.credit, 'wave:432')
  assert.equal(wave.signal.line.amount, 0)
  assert.equal(wave.signal.balanced, true)
  assert.equal(wave.signal.sealed, true)
  assert.equal(wave.signal.arrivesWith, 'teleport')
  assert.equal(wave.signal.separateCarrier, false)
  assert.equal(wave.signal.faster, true)
  assert.equal(wave.signal.ftl, false)
  assert.equal(wave.signal.proof.holds, true)
  assert.equal(wave.signal.proof.pauli.every((row) => row.agrees && row.silent), true)
  assert.equal(wave.signal.measured, false)
  assert.equal(wave.signal.processed, false)
  assert.equal(wave.signal.physics, false)
  assert.equal(wave.signal.heal.from, false)
  assert.equal(wave.signal.heal.next, true)
  assert.equal(wave.signal.heal.sent, false)
  assert.equal(wave.signal.heal.healed, false)
  assert.equal(wave.fetched, false)
  assert.equal(wave.written, false)
  assert.equal(wave.signal.payload[0]?.id, 'iso-16')
})

