// Qpu/General/Textbook.lean is written in Lean. This reads it: each textbook theorem is a doc comment
// `/-- <sentence> (examples: a, b) -/`, the theorem below it, an optional `example` testing it, and then the
// theorems that reflect it (`<key>_reflected`, `_contrapositive`, `_converse`, `_converse_refuted`), which belong to it.
// The index rendered from this (textbook-index.ts) is what the TypeScript side reads; nothing is typed twice.
export type TextbookRow = { key: string; lean: string; says: string; examples: string[]; example?: string }

const DERIVED = /_(reflected|contrapositive|converse_refuted|converse)$/

export const parseTextbook = (lean: string): TextbookRow[] => {
  const lines = lean.split('\n'), rows: TextbookRow[] = []
  for (let i = 0; i < lines.length; i++) {
    const doc = /^\/-- (.*) \(examples: (.*)\) -\/$/.exec(lines[i]!)
    if (!doc) continue
    const body: string[] = []
    for (let j = i + 1; j < lines.length && !lines[j]!.startsWith('/-- '); j++) body.push(lines[j]!)
    while (body.length && body.at(-1) === '') body.pop()
    const key = /^theorem (\S+)/.exec(body[0] ?? '')?.[1]
    if (!key) continue
    const base = rows.at(-1)?.key
    if (base && key.startsWith(`${base}_`) && DERIVED.test(key) && key.replace(DERIVED, '') === base) continue
    const at = body.findIndex((line) => line.startsWith('example '))
    const example = at < 0 ? undefined : body.slice(at).join('\n')
    rows.push({ key, lean: (at < 0 ? body : body.slice(0, at)).join('\n'), says: doc[1]!, examples: doc[2] === 'none yet' ? [] : doc[2]!.split(', '), ...(example ? { example } : {}) })
  }
  return rows
}

/** textbook-index.ts, rendered from the Lean file's text. */
export const textbookIndex = (lean: string) => {
  const path = 'src/quantum/processing/textbook-index.ts', rows = parseTextbook(lean)
  const text = ['// GENERATED by src/scripts/leanDerived.ts from Qpu/General/Textbook.lean. Do not edit: the Lean file is the author.', "import type { TextbookRow } from './textbook-parse.ts'", 'export const TEXTBOOK_INDEX: readonly TextbookRow[] = [', ...rows.map((row) => `  ${JSON.stringify(row)},`), ']', ''].join('\n')
  return { phase: 'scripts-textbook-index' as const, path, text, theorems: rows.length, says: `${rows.length} textbook theorem(s) read from the Lean file` }
}
