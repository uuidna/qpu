/** ISO/IEC/IEEE 29119-3 test case. Identifier: 124875 bouncing in 3690 is one UUID whose reverse is the reflection, and 3690 is entangled with 7410. */
test('124875 bouncing in 3690 is one UUID whose reverse is the reflection, and 3690 is entangled with 7410', () => {
  const s = sequenceUuid()
  const sigma = (d: number) => (d === 0 ? 0 : 10 - d)
  const reading = channel(s.uuid)
  const forward = [...[...reading.handle].map((c) => parseInt(c, 16)), ...reading.program, ...[...reading.tail].map((c) => parseInt(c, 16))]
  assert.equal(s.sequence, '012487536901')
  assert.equal(s.reflected, '098623574109')
  assert.equal(s.reversed, '901475326890')
  assert.equal(s.tail, s.sequence)
  assert.equal(`${s.handle}${s.program.slice(0, 4).map((n) => n.toString(16)).join('')}`, s.reversed)
  assert.equal(s.sku, s.handle)
  assert.equal(reading.sku, s.sku)
  assert.deepEqual(s.entangled.map((e) => e.court), [3, 6, 9, 0])
  assert.deepEqual(s.entangled.map((e) => e.partner), [7, 4, 1, 0])
  assert.deepEqual(s.entangled.map((e) => e.sum), [10, 10, 10, 0])
  assert.equal(forward.every((d, i) => forward[forward.length - 1 - i] === sigma(d)), true)
  assert.equal(s.reflection.map(sigma).join(), s.circle.join())
  assert.equal(s.sealed, true)
  assert.equal(s.holds, true)
  const n = numerology(s.circuit)
  assert.equal(n.sum, 27)
  assert.equal(n.root, 9)
  assert.deepEqual(n.trinity, [3, 6, 9])
  assert.equal(numerology(s.court).root, n.root)
  assert.equal(numerology(s.partner).root, 3)
  assert.equal(n.trinity.includes(numerology(s.partner).root), true)
  const door = call('verify', { numerology: true }).result?.structuredContent
  assert.equal(door.phase, 'simulated')
  assert.equal(door.qubits, 4)
  assert.equal(door.entangled, true)
  assert.equal(door.occupied.length, 4)
  assert.deepEqual(door.occupied.map((o: { court: number; partner: number }) => [o.court, o.partner]), [[3, 7], [6, 4], [9, 1], [0, 0]])
  assert.ok(door.occupied.every((o: { probability: number }) => Math.abs(o.probability - 0.25) < 1e-12))
})

