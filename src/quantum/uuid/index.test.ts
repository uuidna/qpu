/** ISO/IEC/IEEE 29119-3 test case. Identifier: uuid is deterministic, RFC-shaped, and the seal it mints holds (version decided, variant 8..b). */
test('uuid is deterministic, RFC-shaped, and the seal it mints holds (version decided, variant 8..b)', () => {
  const a = uuid('hello'), b = uuid('hello')
  assert.equal(a, b)
  assert.match(a, /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/)
  const s = seal(a)
  assert.ok(s.valid && s.shape && s.variant && s.version.agree, JSON.stringify(s))
  assert.notEqual(uuid('hello'), uuid('hello '))
  assert.equal(fold('').length, 16)
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: a tampered middle breaks the seal (the version the content decides no longer matches). */
test('a tampered middle breaks the seal (the version the content decides no longer matches)', () => {
  const u = uuid('tamper me')
  const hex = u.replace(/-/g, '')
  const flipped = `${hex.slice(0, 13)}${hex[13] === '0' ? '1' : '0'}${hex.slice(14)}` // flip a program nibble, keep the version slot
  const tampered = `${flipped.slice(0, 8)}-${flipped.slice(8, 12)}-${flipped.slice(12, 16)}-${flipped.slice(16, 20)}-${flipped.slice(20)}`
  assert.equal(seal(tampered).valid, false)
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: canonicalText separates a BigInt, a number and a string, and never throws on a BigInt (memo works). */
test('canonicalText separates a BigInt, a number and a string, and never throws on a BigInt (memo works)', () => {
  assert.equal(canonicalText(10n), '"10n"')
  assert.notEqual(canonicalText(10n), canonicalText(10))
  assert.notEqual(canonicalText(10n), canonicalText('10'))
  const id = memo((x: bigint) => x * 2n)
  assert.equal(id(21n), 42n) // previously threw: "Do not know how to serialize a BigInt"
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: canonicalText gives distinct text for distinct Dates (no {} collision) and sorts object keys. */
test('canonicalText gives distinct text for distinct Dates (no {} collision) and sorts object keys', () => {
  assert.notEqual(canonicalText(new Date('2020-01-01')), canonicalText(new Date('2021-01-01')))
  assert.equal(canonicalText(new Date('2020-01-01T00:00:00.000Z')), '"2020-01-01T00:00:00.000Z"')
  assert.equal(canonicalText({ b: 1, a: 2 }), canonicalText({ a: 2, b: 1 }))
  assert.equal(canonicalText(undefined), 'null')
  assert.equal(canonicalText(Infinity), '"Infinity"')
  assert.equal(canonicalText([1, 'x', true]), '[1,"x",true]')
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: reflection applied twice returns the parts (σ_d(σ_d(x)) = x on handle, program, tail). */
test('reflection applied twice returns the parts (σ_d(σ_d(x)) = x on handle, program, tail)', () => {
  const u = uuid('reflect'), ch = channel(u)
  const back = reflection(reflection(u).mirror)
  assert.equal(back.handle, ch.handle)
  assert.deepEqual(back.program, ch.program)
  assert.equal(back.tail, ch.tail)
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: neighbours gives six sealed one-step neighbours and the step back returns the program. */
test('neighbours gives six sealed one-step neighbours and the step back returns the program', () => {
  const u = uuid('walk'), ch = channel(u)
  const nb = neighbours(u)
  assert.equal(nb.neighbours.length, 6)
  assert.ok(nb.neighbours.every((n) => n.sealed), 'every neighbour is a valid sealed address')
  for (const n of nb.neighbours) {
    const back = neighbours(n.uuid).neighbours.find((m) => m.axis === n.axis && m.step === -n.step)
    assert.ok(back, `${n.axis} has a step back`)
    assert.deepEqual(channel(back!.uuid).program, ch.program, `step ${n.axis} ${n.step} then back returns the program`)
  }
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: uuidFromParts round-trips through channel and rejects malformed parts. */
test('uuidFromParts round-trips through channel and rejects malformed parts', () => {
  const u = uuid('parts'), ch = channel(u)
  const rebuilt = uuidFromParts(ch.handle, ch.program, ch.tail)
  const rc = channel(rebuilt)
  assert.equal(rc.handle, ch.handle)
  assert.deepEqual(rc.program, ch.program)
  assert.equal(rc.tail, ch.tail)
  assert.ok(seal(rebuilt).valid)
  assert.throws(() => uuidFromParts('xyz', ch.program, ch.tail))
  assert.throws(() => uuidFromParts(ch.handle, [1, 2, 3], ch.tail))
  assert.throws(() => uuidFromParts(ch.handle, ch.program.map(() => 16), ch.tail))
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: the mixed-radix compositions are a bijection: index → digits → index round-trips, and a rosetta keeps the count. */
test('the mixed-radix compositions are a bijection: index → digits → index round-trips, and a rosetta keeps the count', () => {
  const radices = [6, 7, 2]
  assert.equal(compositions(radices), 84n)
  for (const i of [0n, 1n, 41n, 83n]) {
    const d = composition(radices, i)
    assert.equal(compositionIndex(radices, d), i)
    assert.ok(d.every((x, k) => x >= 0 && x < radices[k]!))
  }
  const r = rosetta(radices)
  assert.equal(r.scale, 84n)
  for (const i of [0n, 13n, 83n]) assert.equal(r.from(r.to(i)), i) // to/from are inverse
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: harmonicDefaults always picks a combination within the schema, from the referrer or the a432 key. */
test('harmonicDefaults always picks a combination within the schema, from the referrer or the a432 key', () => {
  const schema = { properties: { a: { enum: ['x', 'y', 'z'] }, b: { enum: [1, 2] } } }
  const d1 = harmonicDefaults(schema)
  assert.equal(d1.count, 6n)
  assert.ok(d1.index >= 0n && d1.index < 6n && d1.from === 'a432')
  assert.ok(schema.properties.a.enum.includes(d1.defaults.a as string) && schema.properties.b.enum.includes(d1.defaults.b as number))
  const d2 = harmonicDefaults(schema, uuid('a-referrer'))
  assert.equal(d2.from, 'referrer')
  assert.ok(d2.index >= 0n && d2.index < 6n)
})

/** ISO/IEC/IEEE 29119-3 test case. Identifier: presentation and stream read a hex as itself: a nibble is one of sixteen choices, a row styled from itself. */
test('presentation and stream read a hex as itself: a nibble is one of sixteen choices, a row styled from itself', () => {
  const u = uuid('present')
  const p = presentation(u)
  assert.equal(p.nibbles, 32)
  assert.ok(p.parts.every((x) => x.item.startsWith('qpu-') && (x.variant === 'solid' || x.variant === 'outline')))
  assert.throws(() => presentation('zzzz'))
  const s = stream([uuid('a'), uuid('b'), uuid('c')], { sort: 'hue' })
  assert.equal(s.stream, 3)
  assert.ok(s.rows.every((r, i) => i === 0 || r.hue >= s.rows[i - 1]!.hue), 'sorted by hue ascending')
  const styled = style(u)
  // one cascade source: the presentation's accent is the one the block wears inline
  const b = block('present', {}, null, '', 'x')
  assert.ok(styled.hue >= 0 && styled.hue < 360 && styled.vars['--qpu-accent'] === p.style['--qpu-accent'] && b.html.includes(`style="${style(b.id).css};`) && style(b.id).vars['--qpu-accent'] === b.theme.accent)
})

